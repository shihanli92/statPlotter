/** Path segments that would reach an object's prototype instead of its own data. */
const UNSAFE_KEYS = new Set(['__proto__', 'constructor', 'prototype'])

function getNode(doc: Project, id: NodeId): DocNode {
  const node = nodeById(doc.nodes, id)
  if (!node) throw new CommandError(`no node ${id}`)
  return node
}

/** A folder of the navigator (roadmap 40). */
function getFolder(doc: Project, id: FolderId) {
  const f = doc.folders?.find((x) => x.id === id)
  if (!f) throw new CommandError(`no folder ${id}`)
  return f
}

/** Takes sheets out of whatever folder they are in. */
function unfile(doc: Project, ids: readonly NodeId[]) {
  const set = new Set(ids)
  for (const f of doc.folders ?? [])
    if (f.members.some((id) => set.has(id))) f.members = f.members.filter((id) => !set.has(id))
}

/** Folders' integrity after a structural change (one level of nesting, parents that exist). */
function checkFolders(doc: Project) {
  const issue = folderIssues(doc.folders, (id) => !!nodeById(doc.nodes, id))[0]
  if (issue) throw new CommandError(issue.message)
}

/** The node a new node is made from, whose folder it joins (roadmap 40). */
function sourceOf(node: DocNode): NodeId | undefined {
  if (node.kind === 'analysis') return node.input?.source
  if (node.kind === 'graph') return node.seriesSource?.table
  return undefined
}

function getInfo(doc: Project, id: NodeId): InfoNode {
  const node = getNode(doc, id)
  if (node.kind !== 'info') throw new CommandError(`${id} is not an info sheet`)
  return node
}

/** Rewrites info references in every table's formulas (roadmap 40: renames follow). */
function renameInfoRefs(doc: Project, rename: (prefix: string, label: string) => string | null) {
  for (const node of Object.values(doc.nodes)) {
    if (node.kind !== 'table') continue
    for (const ds of node.dataSets) {
      if (ds.formula === undefined || !ds.formula.includes(':')) continue
      const next = renameInfoInFormula(ds.formula, rename)
      if (next !== null) ds.formula = next
    }
  }
}

