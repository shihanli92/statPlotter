function cellColumn(t: DataTable, addr: CellAddr) {
  const cols = addr.col === 'x' ? t.x?.subcolumns : getColumn(t, addr.col).subcolumns
  const col = Number.isInteger(addr.sub) ? cols?.[addr.sub] : undefined
  if (!col) throw new CommandError(`no subcolumn ${addr.sub} in ${String(addr.col)}`)
  return col
}

/** A column of nulls (an empty column or row titles). */
const nulls = (n: number): null[] => Array.from({ length: n }, () => null)

/** The X subcolumns and every data set's subcolumns. */
const allSubcolumns = (t: DataTable) => [
  ...(t.x?.subcolumns ?? []),
  ...t.dataSets.flatMap((d) => d.subcolumns),
]

/** The rich form a title command stores: formatted runs spelling the title, else none. */
const richFor = (title: string | null, rich: RichText | undefined): RichText | undefined => {
  const r = richTitleOf(rich)
  return r && title !== null && richPlain(r) === title ? r : undefined
}

/** Sets or clears entry `i` of a sparse per-index list of rich forms; null when none is left. */
function setRichAt(
  list: (RichText | null)[] | undefined,
  length: number,
  i: number,
  rich: RichText | undefined,
): (RichText | null)[] | null {
  if (!rich && !list) return null
  const out = list ?? []
  while (out.length < length) out.push(null)
  out[i] = rich ?? null
  return out.some((r) => r !== null) ? out : null
}

/** The highest row edited (−1 for none), by a loop: pastes can hold more edits than arguments. */
function maxEditRow(edits: readonly { row: number }[]): number {
  let max = -1
  for (const e of edits) if (e.row > max) max = e.row
  return max
}

function insertRows(t: DataTable, at: number, count: number) {
  if (count <= 0) return
  // New rows are empty: null, and not excluded.
  const runs: [number, number][] = [[at, count]]
  mapRowArrays(t, (arr, fill) => withRuns<unknown>(arr, runs, undefined, fill) as never)
  t.rowCount += count
}

/** An array as it stands in the command (a draft's current contents), without Immer's traps. */
const plain = <T>(a: T[]): T[] => (isDraft(a) ? (current(a as never) as T[]) : a)
/** A subcolumn as it stands (a draft's current contents). */
const plainColumn = <T extends object>(c: T): T => (isDraft(c) ? (current(c as never) as T) : c)

/**
 * Replaces every per-row array of a table with `f` of it (`fill`: what a new row holds). Whole
 * arrays (roadmap 34e): one patch each, where splicing a draft made a patch per shifted cell.
 */
function mapRowArrays(
  t: DataTable,
  f: <T>(arr: readonly T[], fill: T | null | false) => (T | null | false)[],
) {
  for (const c of allSubcolumns(t)) {
    c.values = f(plain(c.values), null) as (number | null)[]
    if (c.excluded) c.excluded = f(plain(c.excluded), false) as boolean[]
    if (c.limit) c.limit = f(plain(c.limit), null) as typeof c.limit
  }
  for (const d of t.dataSets) if (d.text) d.text = f(plain(d.text), null) as (string | null)[]
  if (t.rowTitles) t.rowTitles = f(plain(t.rowTitles), null) as (string | null)[]
  if (t.rowTitlesRich) t.rowTitlesRich = f(plain(t.rowTitlesRich), null) as (RichText | null)[]
}

/**
 * Puts row `order[i]` at row `i` in every per-row array (rows past `order.length` stay). Arrays
 * are replaced whole: one patch each, not one per cell.
 */
function permuteRows(t: DataTable, order: readonly number[]) {
  const permuted = <T>(arr: readonly T[]): T[] => {
    const out = arr.slice()
    for (let i = 0; i < order.length; i++) out[i] = arr[order[i]!]!
    return out
  }
  for (const c of allSubcolumns(t)) {
    c.values = permuted(c.values)
    if (c.excluded) c.excluded = permuted(c.excluded)
    if (c.limit) c.limit = permuted(c.limit)
  }
  for (const d of t.dataSets) if (d.text) d.text = permuted(d.text)
  if (t.rowTitles) t.rowTitles = permuted(t.rowTitles)
  if (t.rowTitlesRich) t.rowTitlesRich = permuted(t.rowTitlesRich)
}

/** Drops all-false exclusion arrays and flag-less limit arrays so the document stays minimal. */
function pruneExclusions(t: DataTable) {
  for (const c of allSubcolumns(t)) {
    if (c.excluded && !c.excluded.includes(true)) delete c.excluded
    if (c.limit?.every((f) => f === null)) delete c.limit
  }
}

/** Text and calculated variables belong to multiple-variables tables. */
function checkVariables(t: DataTable) {
  if (t.tableKind !== 'multipleVariables')
    throw new CommandError('text and calculated variables belong to multiple-variables tables')
}

/**
 * A table with the document's info constants bound, for its formulas (roadmap 40): the project's
 * memoised constants (`infoConstants`, as the grid and graphs bind them), so a table the command
 * has not changed yet is the bound table they evaluated (audit 2, M17). Made from the info sheets
 * as they stand, never drafts: the constants outlive the command.
 */
function bound(doc: Project, t: DataTable): DataTable {
  const plain = isDraft(t) ? current(t) : t
  if (!mayNameInfo(plain)) return plain
  const sheets = infoSheets(doc).map((s) => (isDraft(s) ? current(s) : s))
  const nodes = Object.fromEntries(sheets.map((s) => [s.id, s]))
  return withConstants(plain, infoConstants({ nodes, order: sheets.map((s) => s.id) }))
}

/**
 * What a calculated variable gives now (the document as the command sees it), its formulas
 * evaluated once: its text (roadmap 38; null for a number one) and its values.
 */
function formulaOf(doc: Project, t: DataTable, id: ColumnId) {
  const f = tableFormulas(bound(doc, t)).get(id)
  const text = f?.text
  return {
    text: text ? Array.from({ length: t.rowCount }, (_, r) => text[r] ?? null) : null,
    values: (): (number | null)[] =>
      Array.from({ length: t.rowCount }, (_, r) => {
        const v = f?.values[r]
        return v === undefined || Number.isNaN(v) ? null : tidyNumber(v)
      }),
  }
}

/**
 * Why an XY table's data set can't swap with X (roadmap 38), or null when it can: X holds one
 * number per row, so the table must have one value per row and plain X values.
 */
export function swapXYProblem(t: DataTable, dataSet: string): string | null {
  if (t.tableKind !== 'xy' || !t.x) return 'Swap X and Y works on XY tables.'
  if (!t.dataSets.some((d) => d.id === dataSet)) return `no column ${dataSet}`
  if (t.yFormat.type !== 'replicates' || t.yFormat.count !== 1)
    return 'X has one value per row: a table with replicates or summary data can’t swap X and Y.'
  if (t.x.xFormat === 'numbersWithError' || t.x.subcolumns.length !== 1)
    return 'X values with error bars can’t become Y values.'
  return null
}

/** Makes a variable plain numeric with these values (no text, no formula, no exclusions). */
function setNumbers(ds: DataSetColumn, values: (number | null)[]) {
  delete ds.text
  delete ds.formula
  ds.subcolumns = [{ type: 'number', values }]
}

function isSummaryColumnTable(t: DataTable) {
  return t.tableKind === 'column' && t.yFormat.type === 'summary'
}

/** No data set keys to replace: `mapKey` then maps only rows. */
const NO_KEYS: KeyMap = new Map()

/**
 * Graph row slices, point formats and labelled rows, and grouped-graph bracket cells address rows
 * by index (and the comparison keys of grouped ANOVAs embed row indices), so inserting or
 * deleting rows must move them along. `map` gives a row's new
 * index, or null when the row was deleted; a bracket on a deleted row is removed. Result layers
 * reading a comparison of an analysis of the table follow its rows too, on any graph (audit 2,
 * M4); a field reading a deleted row's comparison goes (it reads "—").
 */
function remapGraphRows(doc: Project, table: NodeId, map: (row: number) => number | null) {
  /** The rows of a list that are left, moved; undefined when nothing changes. */
  const remapList = (rows: readonly number[]): number[] | undefined => {
    const next = rows.map(map).filter((r): r is number => r !== null)
    return next.length !== rows.length || next.some((r, i) => r !== rows[i]) ? next : undefined
  }
  /** Only keys of analyses of this table carry this table's row indices. */
  const onTable = (id: NodeId) => {
    const analysis = nodeById(doc.nodes, id)
    return analysis?.kind === 'analysis' && analysis.input.source === table
  }
  const resultKey = (key: string, analysis: NodeId) =>
    onTable(analysis) ? mapKey(key, NO_KEYS, map) : key
  for (const node of Object.values(doc.nodes)) {
    if (node.kind !== 'graph') continue
    const plain = isDraft(node) ? current(node) : node
    if (node.seriesSource.table !== table) {
      assignChanged(node, plain, mapGraphRefs(plain, { resultKey }))
      continue
    }
    // Row slices, labelled rows (point labels), single-point formats and bracket cells follow
    // their rows; a deleted row's formats and brackets go with it (`graphRefs` finds them all).
    const next = mapGraphRefs(plain, {
      rows: (rows) => remapList(rows) ?? 'keep',
      row: map,
      resultKey,
      bracket: (a) => {
        if (a.rowA === undefined && a.rowB === undefined) return 'keep'
        const rowA = a.rowA === undefined ? undefined : map(a.rowA)
        const rowB = a.rowB === undefined ? undefined : map(a.rowB)
        let key: string | null = null
        if (a.label.source === 'analysis')
          key = onTable(a.label.analysis)
            ? mapKey(a.label.comparison, NO_KEYS, map)
            : a.label.comparison
        if (rowA === null || rowB === null || (a.label.source === 'analysis' && key === null))
          return 'drop'
        const out = { ...a }
        if (rowA !== undefined) out.rowA = rowA
        if (rowB !== undefined) out.rowB = rowB
        if (out.label.source === 'analysis' && key !== null && key !== out.label.comparison)
          out.label = { ...out.label, comparison: key }
        return sameBracket(out, a) ? 'keep' : out
      },
    })
    assignChanged(node, plain, next)
  }
}

/**
 * Audit 2 (M3, M15): what names data sets of `table` follows `keys` (a key → another key, or
 * null: gone) — analyses of it and of the result tables computed from it (chains), graphs of any
 * of them, and graphs drawing those analyses' outputs, results or comparisons. Rewritten by
 * `remapNode` (graphs through `mapGraphRefs`: series, identities, layers, aesthetics, mapping,
 * levels, filters, split sets, brackets, outputs, result keys; analyses' inputs, pools and
 * parameters); a key gone is dropped from where it is (a bracket naming it goes).
 */
function remapDataSetKeys(doc: Project, table: NodeId, keys: KeyMap) {
  const from = new Set<NodeId>([table])
  for (let grew = true; grew; ) {
    grew = false
    for (const n of Object.values(doc.nodes))
      if (n.kind === 'analysis' && !from.has(n.id) && from.has(n.input.source)) {
        from.add(n.id)
        grew = true
      }
  }
  // Outputs of these nodes follow (their keys name the data sets): identity node maps.
  const remap: Remap = { nodes: new Map([...from].map((id) => [id, id])), keys }
  for (const node of Object.values(doc.nodes)) {
    const reads =
      node.kind === 'analysis'
        ? from.has(node.input.source)
        : node.kind === 'graph' &&
          graphRefs(node).some(
            (r) =>
              ((r.kind === 'source' || r.kind === 'output' || r.kind === 'analysis') &&
                from.has(r.node)) ||
              (r.kind === 'bracket' &&
                r.annotation.label.source === 'analysis' &&
                from.has(r.annotation.label.analysis)),
          )
    if (!reads) continue
    const plain = (isDraft(node) ? current(node) : node) as DocNode
    const next = remapNode(plain, remap) as unknown as Record<string, unknown>
    // Only the fields that changed are written (the rest of the node stays shared).
    const before = plain as unknown as Record<string, unknown>
    for (const [k, v] of Object.entries(next))
      if (JSON.stringify(v) !== JSON.stringify(before[k]))
        (node as unknown as Record<string, unknown>)[k] = v
    for (const k of Object.keys(before))
      if (!Object.hasOwn(next, k)) delete (node as unknown as Record<string, unknown>)[k]
  }
}

const sameBracket = (
  a: Extract<GraphNode['annotations'][number], { type: 'bracket' }>,
  b: Extract<GraphNode['annotations'][number], { type: 'bracket' }>,
) => JSON.stringify(a) === JSON.stringify(b)

/** Writes the top-level fields `next` changed from `plain` into the (draft) node. */
function assignChanged(node: GraphNode, plain: GraphNode, next: GraphNode) {
  if (next === plain) return
  for (const k of Object.keys(next) as (keyof GraphNode)[])
    if (next[k] !== plain[k]) (node as Record<string, unknown>)[k] = next[k]
}

/** Analyses of the table whose parameters name rows (`ROW_PARAMS`) follow them. */
function remapAnalysisRows(doc: Project, table: NodeId, map: (row: number) => number | null) {
  for (const node of Object.values(doc.nodes)) {
    if (node.kind !== 'analysis' || node.input.source !== table) continue
    if (!Object.hasOwn(ROW_PARAMS, node.analysisId)) continue
    const params = isDraft(node.params) ? current(node.params) : node.params
    const next = remapRowParams(node.analysisId, params, map)
    if (next !== undefined) node.params = next
  }
}

/** Everything that names a table's rows by index follows a row insert, delete or reorder. */
function remapRows(doc: Project, table: NodeId, map: (row: number) => number | null) {
  remapGraphRows(doc, table, map)
  remapAnalysisRows(doc, table, map)
}

/**
 * What removing `id` removes: the node and everything computed from it — analyses of removed
 * data, and graphs of removed tables. A graph that only shows an analysis' output (the
 * analysis' own output graph: no table series, every extra series from removed nodes) goes too;
 * other graphs and layouts stay and only lose their references (see `node.remove`).
 */
export function removalSet(doc: Project, id: NodeId): Set<NodeId> {
  return removalSetOf(doc, [id])
}

/**
 * What removing all of `ids` together removes (roadmap 47: several sheets deleted at once): the
 * union of their cascades, and graphs whose outputs all come from removed nodes even when no one
 * of them removes every output. Removing them one after another removes the same.
 */
export function removalSetOf(doc: Project, ids: readonly NodeId[]): Set<NodeId> {
  const out = new Set<NodeId>(ids)
  let grew = true
  while (grew) {
    grew = false
    for (const node of Object.values(doc.nodes)) {
      if (out.has(node.id)) continue
      let gone: boolean
      if (node.kind === 'layout') gone = false
      else if (node.kind === 'graph') {
        const outputs = graphOutputs(node)
        gone =
          out.has(node.seriesSource.table) ||
          (Array.isArray(node.seriesSource.include) &&
            node.seriesSource.include.length === 0 &&
            outputs.length > 0 &&
            outputs.every((o) => out.has(o.series.ref.node)))
      } else gone = nodeDependencies(node).some((d) => out.has(d))
      if (gone) {
        out.add(node.id)
        grew = true
      }
    }
  }
  return out
}

/**
 * What the user should know before removing `id` (audit 2, M5): for an info sheet, the tables
 * whose formulas read its fields (they would read another sheet's field so labelled, or show an
 * error).
 */
export function removalWarnings(
  doc: Project,
  id: NodeId,
  /** Roadmap 47: tables removed too (several sheets deleted at once) need no warning. */
  doomed: ReadonlySet<NodeId> = new Set(),
): string[] {
  const node = nodeById(doc.nodes, id)
  if (node?.kind !== 'info') return []
  const sheets = infoSheets(doc)
  const out: string[] = []
  for (const n of Object.values(doc.nodes)) {
    if (n.kind !== 'table' || doomed.has(n.id)) continue
    const labels = [
      ...new Set(
        infoReads(n, sheets)
          .filter((r) => r.sheet?.id === id)
          .map((r) => `“${r.label.trim()}”`),
      ),
    ]
    if (labels.length)
      out.push(`The formulas of “${n.name}” read ${labels.join(', ')} from “${node.name}”.`)
  }
  return out
}

/**
 * Drops a surviving graph's outputs (curves) and analysis brackets that reference removed nodes
 * (an outputs layer left with none goes too).
 */
function stripGraphRefs(graph: GraphNode, doomed: ReadonlySet<NodeId>) {
  const plain = isDraft(graph) ? current(graph) : graph
  const next = mapGraphRefs(plain, {
    output: (o) => (doomed.has(o.ref.node) ? 'drop' : 'keep'),
    bracket: (a) =>
      a.label.source === 'analysis' && doomed.has(a.label.analysis) ? 'drop' : 'keep',
    // Roadmap 35: result labels, lines, bands and tables of a removed analysis go too.
    analysis: (node) => (doomed.has(node) ? 'drop' : 'keep'),
  })
  assignChanged(graph, plain, next)
}

/** A graph node by id (a CommandError for anything else). */
function getGraph(doc: Project, id: NodeId): GraphNode {
  const node = getNode(doc, id)
  if (node.kind !== 'graph') throw new CommandError(`${id} is not a graph`)
  return node
}

/** The index of a graph's layer by id (a CommandError when it has none). */
function layerIndex(graph: GraphNode, id: string): number {
  const i = graph.layers.findIndex((l) => l.id === id)
  if (i < 0) throw new CommandError(`no layer ${id} in ${graph.id}`)
  return i
}

/** Drops layer ids no longer in the list from every data set's drawing order. */
function cleanOrders(graph: GraphNode) {
  const ids = new Set(graph.layers.map((l) => l.id))
  for (const id of Object.values(graph.seriesOverrides)) {
    if (!id.order?.some((l) => !ids.has(l))) continue
    const order = id.order.filter((l) => ids.has(l))
    if (order.length) id.order = order
    else delete id.order
  }
}

/** Applies a command to an Immer draft. Throws CommandError on invalid input. */
export function applyCommand(doc: Project, cmd: Command): void {
  if (isTableCommand(cmd)) {
    applyTableCommand(doc, cmd)
    return
  }
  switch (cmd.type) {
    case 'project.setSettings':
      // Values are validated by the store; unknown keys are refused here.
      for (const [key, value] of Object.entries(cmd.settings)) {
        if (!Object.hasOwn(ProjectSettings.shape, key))
          throw new CommandError(`unknown setting ${key}`)
        if (value === undefined) continue
        // A copy, as every command stores (audit 2, M8): the store freezes what it holds.
        ;(doc.settings as Record<string, unknown>)[key] = copyData(value)
      }
      for (const key of cmd.clear ?? []) {
        if (key !== 'style') throw new CommandError(`cannot clear setting ${String(key)}`)
        delete doc.settings[key]
      }
      return

    case 'node.add': {
      if (typeof cmd.node.id !== 'string' || !ID_PATTERN.test(cmd.node.id))
        throw new CommandError(`invalid node id ${String(cmd.node.id)}`)
      if (nodeById(doc.nodes, cmd.node.id))
        throw new CommandError(`node ${cmd.node.id} already exists`)
      // A copy (audit 2, M8): later commands of the batch write inside what the document holds,
      // and the document is frozen; neither may reach the caller's node.
      const node = copyDoc(cmd.node)
      doc.nodes[cmd.node.id] =
        cmd.fresh && node.kind === 'graph'
          ? styledNewGraph(node, isDraft(doc.settings) ? current(doc.settings) : doc.settings)
          : node
      const at = cmd.at ?? doc.order.length
      doc.order.splice(Math.max(0, Math.min(at, doc.order.length)), 0, cmd.node.id)
      // Roadmap 40: into its folder, or its source's.
      const folder =
        cmd.folder === undefined
          ? folderOf(doc.folders, sourceOf(cmd.node) ?? '')?.id
          : (cmd.folder ?? undefined)
      if (folder !== undefined) getFolder(doc, folder).members.push(cmd.node.id)
      return
    }

    case 'node.remove': {
      getNode(doc, cmd.id)
      const doomed = removalSet(doc, cmd.id)
      // Survivors only lose their references to removed nodes: layouts their graph items, graphs
      // the curves (extra series) and live brackets of removed analyses.
      for (const node of Object.values(doc.nodes)) {
        if (doomed.has(node.id)) continue
        if (node.kind === 'layout') {
          // Graphs of removed graphs and tables of removed tables or analyses.
          const gone = (it: (typeof node.items)[number]) =>
            (it.type === 'graph' && doomed.has(it.graph)) ||
            (it.type === 'table' && doomed.has(it.source.node))
          if (node.items.some(gone)) node.items = node.items.filter((it) => !gone(it))
        } else if (node.kind === 'graph') stripGraphRefs(node, doomed)
      }
      for (const id of doomed) delete doc.nodes[id]
      doc.order = doc.order.filter((id) => !doomed.has(id))
      // Roadmap 40: folders keep the sheets left (folders themselves stay).
      for (const f of doc.folders ?? [])
        if (f.members.some((id) => doomed.has(id)))
          f.members = f.members.filter((id) => !doomed.has(id))
      return
    }

    case 'node.rename': {
      const node = getNode(doc, cmd.id)
      // Roadmap 40: formulas naming this info sheet ([Sheet: label]) follow its new name.
      if (node.kind === 'info' && !sameInfoName(node.name, cmd.name)) {
        const named = infoSheets(doc).find((s) => sameInfoName(s.name, node.name))
        if (named?.id === node.id && !sameInfoName(node.name, INFO_PREFIX))
          renameInfoRefs(doc, (prefix, label) =>
            sameInfoName(prefix, node.name) ? `${cmd.name.trim()}: ${label}` : null,
          )
      }
      node.name = cmd.name
      // Roadmap 51d (U23): a name typed by the user no longer follows the method.
      if (node.kind === 'analysis') delete node.autoName
      return
    }

    case 'folder.add': {
      const f = cmd.folder
      if (typeof f?.id !== 'string' || !ID_PATTERN.test(f.id))
        throw new CommandError(`invalid folder id ${String(f?.id)}`)
      if (typeof f.name !== 'string') throw new CommandError('a folder needs a name')
      const folders = doc.folders ?? []
      if (folders.some((x) => x.id === f.id)) throw new CommandError(`folder ${f.id} exists`)
      const members = [...(cmd.members ?? [])]
      for (const id of members) getNode(doc, id)
      unfile(doc, members)
      const next = {
        id: f.id,
        name: f.name,
        ...(f.parent !== undefined ? { parent: f.parent } : {}),
        members,
      }
      const at = cmd.at ?? folders.length
      if (!doc.folders) doc.folders = []
      doc.folders.splice(Math.max(0, Math.min(at, doc.folders.length)), 0, next)
      checkFolders(doc)
      return
    }

    case 'folder.rename':
      if (typeof cmd.name !== 'string') throw new CommandError('a folder needs a name')
      getFolder(doc, cmd.id).name = cmd.name
      return

    case 'folder.remove': {
      const f = getFolder(doc, cmd.id)
      const parent = f.parent !== undefined ? getFolder(doc, f.parent) : undefined
      if (parent) parent.members.push(...f.members)
      const folders = doc.folders!
      for (const sub of folders) if (sub.parent === f.id) delete sub.parent
      doc.folders = folders.filter((x) => x.id !== f.id)
      if (!doc.folders.length) delete doc.folders
      return
    }

    case 'folder.move': {
      const f = getFolder(doc, cmd.id)
      const folders = doc.folders!
      const from = folders.findIndex((x) => x.id === f.id)
      folders.splice(from, 1)
      if (cmd.parent === null) delete f.parent
      else f.parent = cmd.parent
      const at = cmd.at ?? folders.length
      folders.splice(Math.max(0, Math.min(at, folders.length)), 0, f)
      checkFolders(doc)
      return
    }

    case 'folder.file': {
      if (!Array.isArray(cmd.ids)) throw new CommandError('ids are a list')
      for (const id of cmd.ids) getNode(doc, id)
      if (cmd.folder !== null) getFolder(doc, cmd.folder)
      unfile(doc, cmd.ids)
      if (cmd.folder !== null) getFolder(doc, cmd.folder).members.push(...cmd.ids)
      return
    }

    case 'info.setField': {
      const sheet = getInfo(doc, cmd.id)
      checkIndex(cmd.index, 'field index')
      const field = sheet.fields[cmd.index]
      if (!field) throw new CommandError(`no field ${cmd.index} in ${cmd.id}`)
      if (cmd.label !== undefined && !sameInfoName(cmd.label, field.label) && field.label.trim()) {
        const old = field.label
        const first = (s: InfoNode) => s.fields.findIndex((x) => sameInfoName(x.label, old))
        const own = first(sheet) === cmd.index
        // [Info: old] names this field when no sheet before it has one so labelled.
        const holder = infoSheets(doc).find((s) => first(s) >= 0)
        const viaInfo = own && holder?.id === sheet.id
        const byName = infoSheets(doc).find((s) => sameInfoName(s.name, sheet.name))
        const viaSheet = own && byName?.id === sheet.id
        const label = cmd.label.trim()
        renameInfoRefs(doc, (prefix, named) => {
          if (!sameInfoName(named, old)) return null
          const isInfo = sameInfoName(prefix, INFO_PREFIX)
          return (isInfo && viaInfo) || (!isInfo && viaSheet && sameInfoName(prefix, sheet.name))
            ? `${prefix}: ${label}`
            : null
        })
      }
      if (cmd.label !== undefined) field.label = cmd.label
      if (cmd.value !== undefined) field.value = cmd.value
      return
    }

    case 'info.setFields': {
      const sheet = getInfo(doc, cmd.id)
      if (!Array.isArray(cmd.fields)) throw new CommandError('fields are a list')
      sheet.fields = copyData(cmd.fields)
      return
    }

    case 'info.setNotes': {
      const sheet = getInfo(doc, cmd.id)
      sheet.notes = cmd.notes
      if (cmd.rich) sheet.notesRich = copyData(cmd.rich)
      else delete sheet.notesRich
      return
    }

    case 'node.replace': {
      const old = getNode(doc, cmd.node.id)
      if (old.kind !== cmd.node.kind) throw new CommandError(`${old.id} is a ${old.kind}`)
      doc.nodes[old.id] = copyDoc(cmd.node)
      return
    }

    case 'node.move': {
      const from = doc.order.indexOf(cmd.id)
      if (from < 0) throw new CommandError(`no node ${cmd.id}`)
      doc.order.splice(from, 1)
      doc.order.splice(Math.max(0, Math.min(cmd.to, doc.order.length)), 0, cmd.id)
      return
    }

    // Copies (audit 2, M8), as `node.add`.
    case 'analysis.setParams':
      getAnalysis(doc, cmd.id).params = copyData(cmd.params)
      return

    case 'analysis.setInput':
      if (!Array.isArray(cmd.dataSets)) throw new CommandError('data sets are a list')
      getAnalysis(doc, cmd.id).input.dataSets = [...cmd.dataSets]
      return

    case 'analysis.recordChange': {
      const a = getAnalysis(doc, cmd.id)
      const history = [...(a.history ?? []), copyData(cmd.change)]
      const over = history.length - MAX_METHOD_HISTORY
      if (over > 0) {
        history.splice(0, over)
        a.historyEarlier = (a.historyEarlier ?? 0) + over
      }
      a.history = history
      return
    }

    case 'node.set': {
      // Generic path setter for graph/analysis properties; the result is schema-validated by the
      // store. `undefined` deletes the key (sparse overrides fall back to theme defaults). A
      // `{ id }` segment resolves to the array element with that id, so a path to a layer stays
      // right when layers move (decision 240).
      if (cmd.path.length === 0) throw new CommandError('empty path')
      const forbidden = new Set(['id', 'kind'])
      if (typeof cmd.path[0] === 'string' && forbidden.has(cmd.path[0])) {
        throw new CommandError(`cannot set ${cmd.path[0]}`)
      }
      for (const key of cmd.path) {
        const bad =
          typeof key === 'string'
            ? UNSAFE_KEYS.has(key)
            : typeof key === 'number'
              ? !Number.isInteger(key) || key < 0
              : typeof key !== 'object' ||
                key === null ||
                Object.keys(key).join() !== 'id' ||
                typeof key.id !== 'string'
        if (bad) throw new CommandError(`invalid path segment ${JSON.stringify(key)}`)
      }
      const shown = cmd.path.map((k) => (typeof k === 'object' ? `{${k.id}}` : String(k))).join('.')
      let target: Record<string | number, unknown> = getNode(doc, cmd.id) as never
      const resolve = (key: GraphPathSegment): string | number | null => {
        if (typeof key !== 'object') return key
        if (!Array.isArray(target))
          throw new CommandError(`path ${shown}: {${key.id}} needs a list`)
        const i = (target as unknown[]).findIndex(
          (x) => typeof x === 'object' && x !== null && (x as { id?: unknown }).id === key.id,
        )
        return i < 0 ? null : i
      }
      for (const seg of cmd.path.slice(0, -1)) {
        const key = resolve(seg)
        if (key === null) {
          if (cmd.value === undefined) return
          throw new CommandError(`path ${shown}: no element ${(seg as { id: string }).id}`)
        }
        let next = Object.hasOwn(target, key) ? target[key] : undefined
        if (next === undefined || next === null) {
          if (cmd.value === undefined) return
          next = {}
          target[key] = next
        }
        if (typeof next !== 'object') throw new CommandError(`path ${shown} crosses a value`)
        target = next as Record<string | number, unknown>
      }
      const last = resolve(cmd.path.at(-1)!)
      if (last === null) {
        if (cmd.value === undefined) return
        throw new CommandError(`path ${shown}: no such element`)
      }
      if (cmd.value === undefined) {
        if (Object.hasOwn(target, last)) delete target[last]
      }
      // A copy: the document freezes what it holds, and a later command in the same batch (or a
      // replay of this one) may write inside the value.
      else target[last] = copyData(cmd.value)
      return
    }

    case 'graph.addLayer': {
      const g = getGraph(doc, cmd.id)
      if (!LayerId.safeParse(cmd.layer?.id).success)
        throw new CommandError(`invalid layer id ${String(cmd.layer?.id)}`)
      if (g.layers.some((l) => l.id === cmd.layer.id))
        throw new CommandError(`layer ${cmd.layer.id} exists`)
      const at = cmd.at ?? g.layers.length
      g.layers.splice(Math.max(0, Math.min(at, g.layers.length)), 0, copyData(cmd.layer))
      return
    }

    case 'graph.removeLayer': {
      const g = getGraph(doc, cmd.id)
      layerIndex(g, cmd.layer)
      // Its attached layers (error bars, labels on it) and layers drawing its data go with it.
      const gone = new Set([cmd.layer])
      for (let grew = true; grew; ) {
        grew = false
        for (const l of g.layers) {
          if (gone.has(l.id)) continue
          if (
            (l.on !== undefined && gone.has(l.on)) ||
            (l.data?.from === 'layer' && gone.has(l.data.layer))
          ) {
            gone.add(l.id)
            grew = true
          }
        }
      }
      g.layers = g.layers.filter((l) => !gone.has(l.id))
      cleanOrders(g)
      return
    }

    case 'graph.moveLayer': {
      const g = getGraph(doc, cmd.id)
      checkIndex(cmd.to, 'layer position')
      const from = layerIndex(g, cmd.layer)
      const [layer] = g.layers.splice(from, 1)
      g.layers.splice(Math.min(cmd.to, g.layers.length), 0, layer!)
      return
    }

    case 'graph.setLayers': {
      const g = getGraph(doc, cmd.id)
      if (!Array.isArray(cmd.layers)) throw new CommandError('layers are a list')
      g.layers = copyData(cmd.layers)
      if (cmd.frame !== undefined) g.frame = cmd.frame
      if (cmd.look !== undefined) g.look = cmd.look
      if (cmd.preset !== undefined) g.preset = cmd.preset
      cleanOrders(g)
      return
    }
  }
}

/** A command that edits one table (`cmd.table`). */
type TableCommand = Extract<Command, { type: `table.${string}` }>

const isTableCommand = (cmd: Command): cmd is TableCommand => cmd.type.startsWith('table.')

function applyTableCommand(doc: Project, cmd: TableCommand): void {
  const t = getTable(doc, cmd.table)
  switch (cmd.type) {
    case 'table.setCells': {
      for (const e of cmd.edits) checkIndex(e.row, 'row')
      const maxRow = maxEditRow(cmd.edits)
      if (maxRow >= t.rowCount) {
        if (isSummaryColumnTable(t)) throw new CommandError('summary column tables have one row')
        insertRows(t, t.rowCount, maxRow + 1 - t.rowCount)
      }
      for (const e of cmd.edits) {
        if (e.value !== null && !Number.isFinite(e.value)) {
          throw new CommandError(`cell values must be finite numbers or null`)
        }
        if (e.value !== null && e.col !== 'x') {
          const ds = getColumn(t, e.col)
          if (ds.text) throw new CommandError(`“${ds.title}” is a text variable`)
          if (ds.formula !== undefined)
            throw new CommandError(`“${ds.title}” is calculated from its formula`)
        }
        const col = cellColumn(t, e)
        col.values[e.row] = e.value
        // A value typed over a cell imported at a limit is the user's: no longer flagged.
        if (col.limit?.[e.row]) {
          col.limit[e.row] = null
          if (col.limit.every((f) => f === null)) delete col.limit
        }
      }
      return
    }

    case 'table.setLimits': {
      if (cmd.rule === null) {
        delete t.limits
        for (const c of allSubcolumns(t)) delete c.limit
        return
      }
      const rule = LimitRule.safeParse(cmd.rule)
      if (!rule.success) throw new CommandError('not a limit rule')
      t.limits = rule.data
      for (const d of t.dataSets)
        d.subcolumns = d.subcolumns.map((c) => {
          const now = plainColumn(c)
          const next = resubstitute(now, rule.data, d.id)
          return next === now ? c : next
        })
      return
    }

    case 'table.setText': {
      for (const e of cmd.edits) {
        checkIndex(e.row, 'row')
        if (e.value !== null && typeof e.value !== 'string')
          throw new CommandError('text cells hold text or nothing')
        if (!getColumn(t, e.col).text) throw new CommandError('not a text variable')
      }
      const maxRow = maxEditRow(cmd.edits)
      if (maxRow >= t.rowCount) insertRows(t, t.rowCount, maxRow + 1 - t.rowCount)
      for (const e of cmd.edits) {
        const v = e.value === null || e.value.trim() === '' ? null : e.value
        getColumn(t, e.col).text![e.row] = v
      }
      return
    }

    case 'table.setVariableType': {
      checkVariables(t)
      if (cmd.to !== 'number' && cmd.to !== 'text') throw new CommandError('number or text')
      for (const id of cmd.ids) {
        const ds = getColumn(t, id)
        const calc = ds.formula !== undefined ? formulaOf(doc, t, id) : null
        const calcText = calc?.text
        if (calcText) {
          // A formula giving text becomes a text variable (or numbers read from its text).
          if (cmd.to === 'text') {
            setNumbers(ds, nulls(t.rowCount))
            ds.text = calcText
          } else
            setNumbers(
              ds,
              calcText.map((s) => (s === null ? null : numberFromText(s))),
            )
          continue
        }
        const numbers = calc
          ? calc.values()
          : ds.text
            ? ds.text.map((s) => (s === null ? null : numberFromText(s)))
            : [...(ds.subcolumns[0]?.values ?? [])]
        if (cmd.to === 'number') {
          if (ds.text || ds.formula !== undefined) setNumbers(ds, numbers)
        } else if (!ds.text) {
          const text = numbers.map((v) => (v === null ? null : textFromNumber(v)))
          setNumbers(ds, nulls(t.rowCount))
          ds.text = Array.from({ length: t.rowCount }, (_, r) => text[r] ?? null)
        }
      }
      return
    }

    case 'table.setFormula': {
      checkVariables(t)
      const ds = getColumn(t, cmd.id)
      if (cmd.formula === null) {
        if (ds.formula !== undefined) {
          // Convert to values: a formula giving text leaves a text variable (roadmap 38).
          const calc = formulaOf(doc, t, cmd.id)
          if (calc.text) {
            setNumbers(ds, nulls(t.rowCount))
            ds.text = calc.text
          } else setNumbers(ds, calc.values())
        }
        return
      }
      if (typeof cmd.formula !== 'string') throw new CommandError('a formula is text')
      const formula = cmd.formula.trim().startsWith('=')
        ? cmd.formula.trim()
        : `=${cmd.formula.trim()}`
      const error = formulaSyntaxError(formula)
      if (error) throw new CommandError(`Formula: ${error}`)
      if (ds.formula === formula) return
      setNumbers(ds, nulls(t.rowCount))
      ds.formula = formula
      return
    }

    case 'table.setExcluded': {
      if (typeof cmd.excluded !== 'boolean') throw new CommandError('excluded must be a boolean')
      for (const addr of cmd.cells) {
        checkIndex(addr.row, 'row')
        const col = cellColumn(t, addr)
        if (addr.row < 0 || addr.row >= t.rowCount)
          throw new CommandError(`row ${addr.row} out of range`)
        if (!col.excluded) {
          if (!cmd.excluded) continue
          col.excluded = Array.from({ length: t.rowCount }, () => false)
        }
        col.excluded[addr.row] = cmd.excluded
      }
      pruneExclusions(t)
      return
    }

    case 'table.insertRows': {
      if (isSummaryColumnTable(t)) throw new CommandError('summary column tables have one row')
      checkIndex(cmd.at, 'row')
      checkIndex(cmd.count, 'row count')
      if (cmd.at > t.rowCount) throw new CommandError(`row ${cmd.at} out of range`)
      if (cmd.count === 0) return
      insertRows(t, cmd.at, cmd.count)
      remapRows(doc, t.id, (r) => (r >= cmd.at ? r + cmd.count : r))
      return
    }

    case 'table.deleteRows': {
      if (isSummaryColumnTable(t)) throw new CommandError('summary column tables have one row')
      const rows = [...new Set(cmd.rows)].sort((a, b) => b - a)
      for (const r of rows) {
        checkIndex(r, 'row')
        if (r >= t.rowCount) throw new CommandError(`row ${r} out of range`)
      }
      if (rows.length) {
        const runs: [number, number][] = []
        for (let i = rows.length - 1; i >= 0; i--) {
          const r = rows[i]!
          const last = runs.at(-1)
          if (last && last[0] + last[1] === r) last[1]++
          else runs.push([r, 1])
        }
        mapRowArrays(t, (arr) => withoutRuns(arr, runs))
        t.rowCount -= rows.length
      }
      pruneExclusions(t)
      if (t.rowTitlesRich?.every((r) => r === null)) delete t.rowTitlesRich
      if (rows.length) {
        const deleted = new Set(rows)
        const ascending = [...rows].reverse()
        remapRows(doc, t.id, (r) => {
          if (deleted.has(r)) return null
          let shift = 0
          for (const d of ascending) {
            if (d >= r) break
            shift++
          }
          return r - shift
        })
      }
      return
    }

    case 'table.setRowTitle': {
      checkIndex(cmd.row, 'row')
      if (cmd.row >= t.rowCount) throw new CommandError(`row ${cmd.row} out of range`)
      if (!t.rowTitles) t.rowTitles = nulls(t.rowCount)
      t.rowTitles[cmd.row] = cmd.title
      const rich = setRichAt(t.rowTitlesRich, t.rowCount, cmd.row, richFor(cmd.title, cmd.rich))
      if (rich) t.rowTitlesRich = rich
      else delete t.rowTitlesRich
      return
    }

    case 'table.showRowTitles': {
      if (cmd.show && !t.rowTitles) t.rowTitles = nulls(t.rowCount)
      if (!cmd.show) {
        t.rowTitles = null
        delete t.rowTitlesRich
      }
      return
    }

    case 'table.setCellsTable': {
      if (cmd.on === null) delete t.cellsTable
      else t.cellsTable = cmd.on
      return
    }

    case 'table.addDataSet': {
      if (t.dataSets.some((d) => d.id === cmd.id)) throw new CommandError(`column ${cmd.id} exists`)
      const ds = createDataSetColumn(
        t.yFormat,
        t.rowCount,
        cmd.title ?? defaultColumnTitle(t.dataSets.length),
      )
      ds.id = cmd.id
      t.dataSets.splice(cmd.at ?? t.dataSets.length, 0, ds)
      return
    }

    case 'table.removeDataSets': {
      const ids = new Set<string>(cmd.ids)
      const gone = t.dataSets.filter((d) => ids.has(d.id)).map((d) => d.id)
      t.dataSets = t.dataSets.filter((d) => !ids.has(d.id))
      if (t.columnWidths && cmd.ids.some((id) => Object.hasOwn(t.columnWidths!, id))) {
        for (const id of cmd.ids) delete t.columnWidths[id]
        if (!Object.keys(t.columnWidths).length) delete t.columnWidths
      }
      // Audit 2 (M15, decision 241): nothing keeps naming them.
      if (gone.length) remapDataSetKeys(doc, t.id, new Map(gone.map((id) => [id, null])))
      return
    }

    case 'table.swapXY': {
      const reason = swapXYProblem(t, cmd.dataSet)
      if (reason) throw new CommandError(reason)
      if (!ID_PATTERN.test(cmd.id) || t.dataSets.some((d) => d.id === cmd.id))
        throw new CommandError(`column id ${cmd.id} is not new`)
      const x = t.x!
      const i = t.dataSets.findIndex((d) => d.id === cmd.dataSet)
      const ds = t.dataSets[i]!
      const old: DataSetColumn = {
        id: cmd.id,
        title: x.title,
        subcolumns: [x.subcolumns[0]!],
        ...(x.titleRich ? { titleRich: x.titleRich } : {}),
        ...(x.display ? { display: x.display } : {}),
      }
      x.subcolumns = [ds.subcolumns[0]!]
      x.title = ds.title
      if (ds.titleRich) x.titleRich = ds.titleRich
      else delete x.titleRich
      if (ds.display) x.display = ds.display
      else delete x.display
      x.xFormat = 'numbers'
      t.dataSets[i] = old
      if (t.columnWidths) {
        const w = t.columnWidths
        const wx = w.x
        const wd = w[cmd.dataSet]
        delete w.x
        delete w[cmd.dataSet]
        if (wd !== undefined) w.x = wd
        if (wx !== undefined) w[cmd.id] = wx
      }
      // What named the data set names the old X now (audit 2, M3: graphs through
      // `mapGraphRefs`, brackets and result keys included; analyses, their outputs and the
      // result tables computed from the table).
      remapDataSetKeys(doc, t.id, new Map([[cmd.dataSet, cmd.id]]))
      return
    }

    case 'table.renameDataSet': {
      const ds = getColumn(t, cmd.id)
      const before = ds.title
      ds.title = cmd.title
      const rich = richFor(cmd.title, cmd.rich)
      if (rich) ds.titleRich = rich
      else delete ds.titleRich
      // Formulas that use the variable follow it to its new name.
      if (before.trim() && before !== cmd.title)
        for (const other of t.dataSets) {
          if (other.formula === undefined) continue
          const next = renameInFormula(other.formula, before, cmd.title)
          if (next !== null) other.formula = next
        }
      return
    }

    case 'table.renameX': {
      if (!t.x) throw new CommandError(`${t.id} has no X column`)
      t.x.title = cmd.title
      const rich = richFor(cmd.title, cmd.rich)
      if (rich) t.x.titleRich = rich
      else delete t.x.titleRich
      return
    }

    case 'table.moveDataSets': {
      checkIndex(cmd.to, 'position')
      const ids = new Set<string>(cmd.ids)
      const moving = t.dataSets.filter((d) => ids.has(d.id))
      if (moving.length !== ids.size) throw new CommandError('no such column')
      const rest = t.dataSets.filter((d) => !ids.has(d.id))
      const next = [...rest]
      next.splice(Math.min(cmd.to, rest.length), 0, ...moving)
      if (next.some((d, i) => d !== t.dataSets[i])) t.dataSets = next
      return
    }

    case 'table.permuteRows': {
      const n = cmd.order.length
      if (n > t.rowCount)
        throw new CommandError(`${n} rows to reorder, the table has ${t.rowCount}`)
      // `to[old]` = the row's new index; every row must appear once.
      const to = new Array<number>(n).fill(-1)
      cmd.order.forEach((old, i) => {
        checkIndex(old, 'row')
        if (old >= n || to[old] !== -1)
          throw new CommandError('rows must be reordered, not repeated')
        to[old] = i
      })
      if (cmd.order.every((old, i) => old === i)) return
      permuteRows(t, cmd.order)
      remapRows(doc, t.id, (r) => (r < n ? to[r]! : r))
      return
    }

    case 'table.setDisplay': {
      const display = cmd.display === null ? null : NumberDisplay.parse(cmd.display)
      for (const col of cmd.cols) {
        const target = col === 'x' ? t.x : getColumn(t, col)
        if (!target) throw new CommandError(`${t.id} has no X column`)
        if (display) target.display = display
        else delete target.display
      }
      return
    }

    case 'table.setColumnWidths': {
      for (const [key, w] of Object.entries(cmd.widths)) {
        if (UNSAFE_KEYS.has(key)) throw new CommandError(`invalid column ${key}`)
        if (w === null) {
          if (t.columnWidths && Object.hasOwn(t.columnWidths, key)) delete t.columnWidths[key]
          continue
        }
        if (typeof w !== 'number' || !Number.isFinite(w))
          throw new CommandError('a column width is a number')
        const width = Math.round(Math.max(MIN_COLUMN_WIDTH, Math.min(MAX_COLUMN_WIDTH, w)))
        if (!t.columnWidths) t.columnWidths = {}
        if (t.columnWidths[key] !== width) t.columnWidths[key] = width
      }
      if (t.columnWidths && !Object.keys(t.columnWidths).length) delete t.columnWidths
      return
    }

    case 'table.setSubcolumnTitle': {
      const ds = getColumn(t, cmd.id)
      checkIndex(cmd.sub, 'subcolumn')
      if (cmd.sub >= ds.subcolumns.length) throw new CommandError(`no subcolumn ${cmd.sub}`)
      if (cmd.title !== null && typeof cmd.title !== 'string')
        throw new CommandError('a subcolumn title is text or null')
      const titles = ds.subcolumnTitles ?? []
      while (titles.length < ds.subcolumns.length) titles.push(null)
      titles[cmd.sub] = cmd.title
      // Keep the document minimal: no array of nothing but untitled subcolumns.
      if (titles.every((v) => v === null)) delete ds.subcolumnTitles
      else ds.subcolumnTitles = titles
      const n = ds.subcolumns.length
      const rich = setRichAt(ds.subcolumnTitlesRich, n, cmd.sub, richFor(cmd.title, cmd.rich))
      if (rich) ds.subcolumnTitlesRich = rich
      else delete ds.subcolumnTitlesRich
      return
    }

    case 'table.setReplicateCount': {
      checkIndex(cmd.count, 'replicate count')
      if (t.yFormat.type !== 'replicates')
        throw new CommandError('only tables of replicate values have subcolumns to add')
      if (cmd.count < 1 || cmd.count > MAX_REPLICATES)
        throw new CommandError(`between 1 and ${MAX_REPLICATES} subcolumns`)
      if (cmd.count === t.yFormat.count) return
      t.yFormat = { type: 'replicates', count: cmd.count }
      for (const ds of t.dataSets) {
        if (ds.subcolumns.length > cmd.count) ds.subcolumns.splice(cmd.count)
        while (ds.subcolumns.length < cmd.count) ds.subcolumns.push(emptyCellColumn(t.rowCount))
        if (ds.subcolumnTitles) {
          ds.subcolumnTitles = ds.subcolumnTitles.slice(0, cmd.count)
          if (ds.subcolumnTitles.every((v) => v === null)) delete ds.subcolumnTitles
        }
        if (ds.subcolumnTitlesRich) {
          ds.subcolumnTitlesRich = ds.subcolumnTitlesRich.slice(0, cmd.count)
          if (ds.subcolumnTitlesRich.every((v) => v === null)) delete ds.subcolumnTitlesRich
        }
      }
      return
    }

    case 'table.setYFormat': {
      const format = YFormat.parse(cmd.format)
      let conv: ReturnType<typeof convertTable>
      try {
        conv = convertTable(isDraft(t) ? current(t) : t, format)
      } catch (e) {
        throw new CommandError(e instanceof Error ? e.message : String(e))
      }
      t.yFormat = format
      t.dataSets.forEach((d, i) => {
        d.subcolumns = conv.subcolumns[i]!
        delete d.subcolumnTitles
        delete d.subcolumnTitlesRich
      })
      if (conv.rowCount !== t.rowCount) {
        const n = conv.rowCount
        t.rowCount = n
        if (t.rowTitles) t.rowTitles = t.rowTitles.slice(0, n)
        if (t.rowTitlesRich) t.rowTitlesRich = t.rowTitlesRich.slice(0, n)
        remapRows(doc, t.id, (r) => (r < n ? r : null))
      }
      return
    }
  }
}
