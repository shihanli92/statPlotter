# Cox proportional-hazards regression (Prism's "Cox proportional hazards regression"), from
# survival::coxph.
#
# input: time, event (0/1), X (rows), names. params: ties ('efron' default | 'breslow'),
# confLevel, ciMethod ('profile' default | 'wald'), interactions (as multreg.R).
#
# Prism's documented methods (Statistics Guide, "Cox proportional hazards regression"):
# - Ties: Prism offers "exact" (its default when there are few ties, all orderings of tied events),
#   Efron (used automatically "when the number of ties is large") and Breslow ("only for purposes
#   of matching results generated by other applications"); stat_cox_math_coefficients_tied_data
#   .htm. We implement Efron (default) and Breslow. DEFERRED: the exact method, and Prism's rule
#   for switching from exact to Efron (undocumented threshold). With no tied event times all
#   three coincide.
# - Coefficient P: Wald z ("The absolute value of Z, calculated as the parameter estimate divided
#   by its standard error"; stat_cox_reg_results_p_values.htm).
# - CIs: profile likelihood ("Prism actually calculates more accurate profile likelihood
#   confidence intervals"; stat_cox_reg_results_parameter_estimates.htm), computed exactly here
#   by uniroot (tol 1e-13) on the signed root, the profile log-likelihood from coxph with the
#   coefficient as an offset; Wald on request. HR limits = exp(limits).
# - Global tests: partial likelihood ratio, Wald and score tests of beta = 0 (Prism's three
#   "hypothesis tests"; stat_cox_regression_gof_tab.htm) = summary(coxph)$logtest/waldtest/sctest.
# - Concordance: Harrell's C (same page), survival::concordance(fit)$concordance.
# - AIC = −2ℓ + 2k (AIC(coxph)). Pseudo R² for Cox (listed by Prism, formula undocumented):
#   DEFERRED.
# - coxph is converged tightly (eps 1e-11, iter.max 100) and restarted from its estimates so the
#   variance is evaluated at the maximum.
# - Degenerate data: aliased covariates (NA in coxph, including a constant column) -> 'singular';
#   no events -> 'singular', everything NaN; coxph's "coefficient may be infinite" warning ->
#   status 'infinite', coefficients and Wald test NaN, LR test at the last iterate (compared
#   loosely), score test exact.

PACKAGES <- c("survival")

suppressPackageStartupMessages(library(survival))

design <- function(input, params) {
  X <- as.matrix(input$X)
  if (is.null(dim(X))) X <- matrix(X, ncol = length(input$names))
  colnames(X) <- input$names
  if (!is.null(params$interactions)) {
    ia <- matrix(params$interactions, ncol = 2)
    for (r in seq_len(nrow(ia))) {
      a <- ia[r, 1] + 1; b <- ia[r, 2] + 1
      X <- cbind(X, X[, a] * X[, b])
      colnames(X)[ncol(X)] <- paste0(input$names[a], ":", input$names[b])
    }
  }
  X
}

CTRL <- coxph.control(eps = 1e-11, iter.max = 100)

nan_test <- list(chiSq = NaN, df = NaN, p = NaN)
tst <- function(v) list(chiSq = unname(v[1]), df = unname(v[2]),
                        p = pchisq(unname(v[1]), unname(v[2]), lower.tail = FALSE))

profile_ll <- function(time, event, M, j, b, ties) {
  off <- b * M[, j]
  others <- M[, -j, drop = FALSE]
  f <- if (ncol(others) == 0) {
    coxph(Surv(time, event) ~ offset(off), ties = ties, control = CTRL)
  } else {
    coxph(Surv(time, event) ~ others + offset(off), ties = ties, control = CTRL)
  }
  f$loglik[length(f$loglik)]
}

oracle <- function(input, params) {
  time <- input$time; event <- input$event
  M <- design(input, params)
  ties <- if (is.null(params$ties)) "efron" else params$ties
  level <- if (is.null(params$confLevel)) 0.95 else params$confLevel
  method <- if (is.null(params$ciMethod)) "profile" else params$ciMethod
  n <- length(time); nev <- sum(event)
  nm <- colnames(M)
  nan_coef <- function(j) list(name = nm[j], estimate = NaN, se = NaN, lower = NaN, upper = NaN,
                               stat = NaN, p = NaN, hazardRatio = NaN, hrLower = NaN,
                               hrUpper = NaN)
  if (nev == 0) {
    return(list(coefficients = lapply(seq_along(nm), nan_coef), n = n, nEvents = 0,
                logLik = 0, nullLogLik = 0, lrTest = nan_test, waldTest = nan_test,
                scoreTest = nan_test, concordance = NULL, status = "singular"))
  }
  warn <- character(0)
  catch <- function(expr) withCallingHandlers(expr, warning = function(w) {
    warn <<- c(warn, conditionMessage(w)); invokeRestart("muffleWarning")
  })
  fit <- catch(coxph(Surv(time, event) ~ M, ties = ties, control = CTRL))
  infinite <- any(grepl("may be infinite", warn))
  fit0 <- fit
  s0 <- summary(fit0)
  cf <- unname(coef(fit))
  aliased <- is.na(cf)
  Mk <- M[, !aliased, drop = FALSE]
  if (!infinite) {
    for (r in 1:2) fit <- coxph(Surv(time, event) ~ Mk, ties = ties, control = CTRL,
                                init = unname(coef(fit))[!is.na(coef(fit))])
  }
  s <- summary(fit)
  # Null log-likelihood and score test are at beta = 0: from the first fit (the restarts begin
  # at the estimates).
  ll0 <- fit0$loglik[1]
  status <- if (infinite) "infinite" else if (fit$iter >= 100) "notConverged" else
    if (any(aliased)) "singular" else "ok"
  ll <- fit$loglik[2]
  k <- sum(!aliased)
  stopifnot(abs(s0$logtest[1] - 2 * (fit0$loglik[2] - ll0)) < 1e-9 * (1 + s0$logtest[1]))
  out <- list(n = n, nEvents = nev, logLik = ll, nullLogLik = ll0,
              lrTest = tst(c(2 * (ll - ll0), k)), scoreTest = tst(s0$sctest), status = status)
  if (infinite) {
    out$coefficients <- lapply(seq_along(nm), nan_coef)
    out$waldTest <- nan_test
    return(out)
  }
  b <- unname(coef(fit)); V <- vcov(fit); se <- sqrt(diag(V))
  z <- qnorm(1 - (1 - level) / 2)
  ci <- if (method == "wald") {
    cbind(b - z * se, b + z * se)
  } else {
    t(sapply(seq_along(b), function(j) {
      signed <- function(v) {
        d <- 2 * (ll - profile_ll(time, event, Mk, j, v, ties))
        sign(v - b[j]) * sqrt(max(0, d))
      }
      lo <- uniroot(function(v) signed(v) + z, c(b[j] - 2 * z * se[j], b[j]),
                    extendInt = "upX", tol = 1e-13)$root
      hi <- uniroot(function(v) signed(v) - z, c(b[j], b[j] + 2 * z * se[j]),
                    extendInt = "upX", tol = 1e-13)$root
      c(lo, hi)
    }))
  }
  coefs <- vector("list", length(nm))
  a <- 0
  for (j in seq_along(nm)) {
    if (aliased[j]) { coefs[[j]] <- nan_coef(j); next }
    a <- a + 1
    zv <- b[a] / se[a]
    coefs[[j]] <- list(name = nm[j], estimate = b[a], se = unname(se[a]), lower = ci[a, 1],
                       upper = ci[a, 2], stat = unname(zv),
                       p = 2 * pnorm(abs(zv), lower.tail = FALSE), hazardRatio = exp(b[a]),
                       hrLower = exp(ci[a, 1]), hrUpper = exp(ci[a, 2]))
  }
  stopifnot(abs(AIC(fit) - (-2 * ll + 2 * sum(!aliased))) < 1e-9 * abs(AIC(fit)))
  # summary()'s Wald test of the restarted fit is relative to its init: compute it at beta = 0.
  wald <- drop(t(b) %*% solve(V, b))
  stopifnot(abs(wald - fit0$wald.test) < 1e-6 * wald)  # summary() rounds it
  c(out, list(coefficients = coefs, waldTest = tst(c(wald, length(b))),
              concordance = unname(concordance(fit)$concordance),
              aic = -2 * ll + 2 * sum(!aliased)))
}
